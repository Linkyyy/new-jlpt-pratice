import { randomBytes, createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";

const code = `JLPT-${randomBytes(12).toString("hex").toUpperCase().match(/.{6}/g).join("-")}`;
const digest = createHash("sha256").update(code).digest("hex");
await writeFile(new URL("../src/lib/activation-code.server.ts", import.meta.url), `// Generated by scripts/rotate-activation-code.mjs. Only the digest is stored.\nexport const ACTIVATION_CODE_DIGEST = "${digest}";\n`);
process.stdout.write(`${code}\n`);
