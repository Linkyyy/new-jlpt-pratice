export const supplementalWordEntries = rows.map(line => {
  const [label, readings, meaning, usage = ''] = line.split('|');
  return {label, readings: readings.split('、'), meaning, usage, source: 'editorial'};
});
const normalize = value => value.normalize('NFKC').replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));
const notes = new Map(supplementalWordEntries.map(entry => [normalize(entry.label), entry]));
export function findSupplementalWordNote(label, reading) {
  const entry = notes.get(normalize(label));
  if (!entry || !entry.readings.some(candidate => normalize(candidate) === normalize(reading))) return null;
  return {meaning: entry.meaning, usage: entry.usage, source: 'editorial'};
}
