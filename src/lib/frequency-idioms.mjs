const lemma = token => (token.basic_form && token.basic_form !== '*' ? token.basic_form : token.surface_form).normalize('NFKC').toLowerCase().replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));

/** Whole consecutive tokens only, including dictionary segmentation changes during inflection. */
export function createIdiomMatcher(tokenize) {
  const firstCharacters = new Map();
  for (const entry of idiomEntries) for (const form of entry.forms) {
    const pattern = tokenize(form).map(lemma).join('');
    if (!pattern.length) continue;
    const candidates = firstCharacters.get(pattern[0]) ?? [];
    if (!candidates.some(candidate => candidate.label === entry.label && candidate.pattern === pattern)) candidates.push({label: entry.label, pattern});
    firstCharacters.set(pattern[0], candidates);
  }
  for (const candidates of firstCharacters.values()) candidates.sort((a, b) => b.pattern.length - a.pattern.length || b.label.length - a.label.length);
  return tokens => {
    const normalized = tokens.map(lemma), matches = [];
    const text = normalized.join(''), starts = [], ends = new Map();
    let offset = 0;
    normalized.forEach((part, index) => { starts.push(offset); offset += part.length; ends.set(offset, index + 1); });
    for (let i = 0; i < normalized.length;) {
      // 気が付く may be three tokens, but 気が付いた one verb plus an auxiliary.
      // Compare joined lemmas while requiring both ends to be source token boundaries.
      const at = starts[i];
      const matched = firstCharacters.get(text[at])?.find(({pattern}) => text.startsWith(pattern, at) && ends.has(at + pattern.length));
      if (matched) { matches.push(matched.label); i = ends.get(at + matched.pattern.length); }
      else i++;
    }
    return matches;
  };
}
